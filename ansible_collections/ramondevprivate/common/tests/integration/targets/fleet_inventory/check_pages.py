"""Structural checks for the pages rendered by fleet_inventory.

Checks that the pages are complete and well-formed Markdown for Obsidian, not their exact wording, so
templates can change without touching this test. Exits non-zero with one line per problem.

Usage: python check_pages.py VAULT_DIR --hosts HOST... [--unreachable HOST...] [--charts]
"""

import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import cast

import yaml

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
GENERATED_NOTE = "%% Generated by ramondevprivate.common.fleet_inventory."
HTML_TAG = re.compile(r"<[^>]*>")
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[|#][^\]]*)?\]\]")
PAGE_LINK = re.compile(r"(?<!!)\[\[([^\]|#]+)\]\]")  # [[host]], not an embed
SUMMARY_EMBED = re.compile(r"!\[\[([^\]|#]+) description#\^summary\]\]")
SEPARATOR_CELL = re.compile(r"^\s*:?-+:?\s*$")
UNESCAPED_PIPE = re.compile(r"(?<!\\)\|")
CALLOUT_WARNING = "> [!warning]"
MERMAID_FENCE = "```mermaid"


def cells(row: str) -> list[str]:
    """Split a table row into cells; escaped pipes belong to the cell."""
    return UNESCAPED_PIPE.split(row.strip())[1:-1]


def tables(text: str) -> list[list[str]]:
    """Find Markdown tables (runs of lines starting with "|"), ignoring fenced code blocks."""
    found: list[list[str]] = []
    current: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("|"):
            current.append(line)
            continue
        if current:
            found.append(current)
            current = []
    if current:
        found.append(current)
    return found


def table_problems(name: str, rows: list[str]) -> list[str]:
    """A table needs a header, a separator line and the same number of cells in every row."""
    header = cells(rows[0])
    if len(rows) < 2 or not all(SEPARATOR_CELL.match(c) for c in cells(rows[1])):
        return [f"{name}: table without separator line: {rows[0]}"]
    return [f"{name}: row has {len(cells(row))} cells, header has {len(header)}: {row}" for row in rows[1:] if len(cells(row)) != len(header)]


def page_problems(path: Path, required_keys: set[str]) -> list[str]:
    """Frontmatter must be valid YAML with the required keys; every table must be well-formed."""
    text = path.read_text()
    match = FRONTMATTER.match(text)
    if match is None:
        return [f"{path.name}: no frontmatter at the start of the file"]
    try:
        frontmatter = cast("object", yaml.safe_load(match.group(1)))  # untyped YAML comes in here
    except yaml.YAMLError as error:
        return [f"{path.name}: frontmatter is not valid YAML: {error}".splitlines()[0]]
    if not isinstance(frontmatter, dict):
        return [f"{path.name}: frontmatter is not a mapping"]
    fields = cast("dict[object, object]", frontmatter)
    keys = {str(k) for k in fields}
    problems = [f"{path.name}: frontmatter lacks {key!r}" for key in sorted(required_keys - keys)]
    tags = fields.get("tags", [])
    if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in cast("list[object]", tags)):
        problems.append(f"{path.name}: tags are not a list of strings: {tags!r}")
    for rows in tables(text):
        problems += table_problems(path.name, rows)
    return problems + markup_problems(path.name, text)


def markup_problems(name: str, text: str) -> list[str]:
    """Host values must not add page markup: no %% comment besides the generated note, no raw HTML but <br>."""
    problems = [
        f"{name}: Obsidian comment outside the generated note: {line!r}" for line in text.splitlines() if "%%" in line and not line.startswith(GENERATED_NOTE)
    ]
    tags = cast("list[str]", HTML_TAG.findall(text))  # one group-less pattern: a list of strings
    problems += [f"{name}: raw HTML {tag!r}" for tag in tags if tag != "<br>"]
    return problems


def server_list_problems(server_list: Path, hosts: frozenset[str]) -> list[str]:
    """The server list links every server page and embeds the summary line of every description note."""
    if not server_list.is_file():
        return [f"{server_list.name} missing"]
    problems = page_problems(server_list, {"last_fetched", "cssclasses"})
    text = server_list.read_text()
    if frozenset(cast("list[str]", PAGE_LINK.findall(text))) != hosts:
        problems.append(f"{server_list.name}: links to the server pages != expected {sorted(hosts)}")
    if frozenset(cast("list[str]", SUMMARY_EMBED.findall(text))) != hosts:
        problems.append(f"{server_list.name}: summary embeds != expected {sorted(hosts)}")
    return problems


@dataclass(frozen=True)
class Args:
    """Typed command line arguments."""

    vault: Path
    hosts: frozenset[str]
    unreachable: frozenset[str]
    charts: bool


def parse_args(argv: list[str]) -> Args:
    """Parse ``VAULT_DIR --hosts HOST... [--unreachable HOST...] [--charts]``."""
    lists: dict[str, list[str]] = {"--hosts": [], "--unreachable": []}
    charts = False
    current: list[str] | None = None
    for arg in argv[1:]:
        if arg == "--charts":
            charts, current = True, None
        elif arg in lists:
            current = lists[arg]
        elif current is not None:
            current.append(arg)
        else:
            message = f"unexpected argument {arg!r}\n{__doc__}"
            raise SystemExit(message)
    if not argv or not lists["--hosts"]:
        message = f"VAULT_DIR and --hosts are required\n{__doc__}"
        raise SystemExit(message)
    return Args(Path(argv[0]), frozenset(lists["--hosts"]), frozenset(lists["--unreachable"]), charts)


def main() -> None:
    """Check the vault and exit non-zero on any problem."""
    args = parse_args(sys.argv[1:])
    hosts, unreachable = args.hosts, args.unreachable

    overview = args.vault / "Overview.md"
    pages = {p.stem: p for p in (args.vault / "Servers").glob("*.md")}
    if not overview.is_file():
        message = f"{overview} missing"
        raise SystemExit(message)
    problems: list[str] = []
    if frozenset(pages) != hosts:
        problems.append(f"server pages {sorted(pages)} != expected {sorted(hosts)}")

    problems += page_problems(overview, {"last_fetched", "cssclasses"})
    for page in pages.values():
        problems += page_problems(page, {"last_fetched", "os", "exposure", "cssclasses"})

    overview_text = overview.read_text()
    links = frozenset(cast("list[str]", WIKILINK.findall(overview_text)))
    if links != hosts:
        problems.append(f"overview links {sorted(links)} != expected {sorted(hosts)}")
    if (MERMAID_FENCE in overview_text) != args.charts:
        problems.append(f"overview charts present: {MERMAID_FENCE in overview_text}, expected: {args.charts}")

    problems += server_list_problems(args.vault / "Server List.md", hosts)

    for name, page in pages.items():
        if (CALLOUT_WARNING in page.read_text()) != (name in unreachable):
            problems.append(f"{name}: 'not updated' callout present != host unreachable ({name in unreachable})")

    if problems:
        message = "\n".join(problems)
        raise SystemExit(message)


if __name__ == "__main__":
    main()
